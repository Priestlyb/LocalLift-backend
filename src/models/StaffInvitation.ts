import mongoose, {
    Document,
    Schema,
    Types,
} from "mongoose";

/**
 * ==========================================
 * STAFF INVITATION DOCUMENT
 * ==========================================
 *
 * Security notes:
 *
 * - The raw invitation token is NEVER stored.
 * - Only the SHA-256 hash of the token is stored.
 * - The token hash is hidden by default.
 * - Invitations automatically expire through
 *   MongoDB's TTL index.
 */
export interface IStaffInvitation
    extends Document {
    /**
     * Name of the invited staff member.
     */
    name: string;

    /**
     * Normalized email address of the
     * invited staff member.
     */
    email: string;

    /**
     * Business owner who created
     * the invitation.
     */
    owner: Types.ObjectId;

    /**
     * SHA-256 hash of the invitation token.
     *
     * IMPORTANT:
     *
     * The raw invitation token must NEVER
     * be stored in MongoDB.
     */
    tokenHash: string;

    /**
     * Invitation expiration timestamp.
     */
    expiresAt: Date;

    /**
     * Timestamp when the invitation
     * was accepted.
     *
     * null = still pending.
     */
    acceptedAt?: Date | null;

    createdAt: Date;
    updatedAt: Date;
}

/**
 * ==========================================
 * SCHEMA
 * ==========================================
 */

const StaffInvitationSchema =
    new Schema<IStaffInvitation>(
        {
            /**
             * ==========================================
             * INVITED STAFF NAME
             * ==========================================
             */
            name: {
                type: String,
                required: true,
                trim: true,

                minlength: 1,
                maxlength: 100,
            },

            /**
             * ==========================================
             * INVITED STAFF EMAIL
             * ==========================================
             *
             * Always store the normalized email.
             */
            email: {
                type: String,
                required: true,

                lowercase: true,
                trim: true,

                minlength: 5,
                maxlength: 254,

                index: true,
            },

            /**
             * ==========================================
             * BUSINESS OWNER
             * ==========================================
             */
            owner: {
                type: Schema.Types.ObjectId,
                ref: "User",
                required: true,

                index: true,
            },

            /**
             * ==========================================
             * INVITATION TOKEN HASH
             * ==========================================
             *
             * The raw token generated by
             * crypto.randomBytes() is NEVER stored.
             *
             * Example:
             *
             * raw token:
             *   abc123...
             *
             * stored value:
             *   SHA256(raw token)
             *
             * The raw token should only exist:
             *
             * 1. During generation.
             * 2. Inside the invitation email URL.
             * 3. When the recipient submits the token.
             */
            tokenHash: {
                type: String,
                required: true,

                unique: true,
                index: true,

                /**
                 * Do not return the token hash
                 * unless explicitly requested.
                 *
                 * Example:
                 *
                 * StaffInvitation.findOne(...)
                 *     .select("+tokenHash")
                 */
                select: false,

                /**
                 * Invitation token hashes should
                 * never change after creation.
                 */
                immutable: true,

                /**
                 * SHA-256 produces exactly
                 * 64 hexadecimal characters.
                 */
                minlength: 64,
                maxlength: 64,

                /**
                 * Make sure the value actually
                 * looks like a SHA-256 hexadecimal hash.
                 */
                match: /^[a-f0-9]{64}$/i,
            },

            /**
             * ==========================================
             * EXPIRATION
             * ==========================================
             *
             * IMPORTANT:
             *
             * Do NOT use `index: true` here.
             *
             * The explicit TTL index below already
             * creates the required index on expiresAt.
             */
            expiresAt: {
                type: Date,
                required: true,
            },

            /**
             * ==========================================
             * ACCEPTED AT
             * ==========================================
             *
             * null = pending invitation
             * Date = invitation already accepted
             */
            acceptedAt: {
                type: Date,
                default: null,

                index: true,
            },
        },

        {
            /**
             * Automatically create:
             *
             * createdAt
             * updatedAt
             */
            timestamps: true,

            /**
             * Reject fields that are not explicitly
             * defined in the schema.
             */
            strict: true,
        }
    );

/**
 * ==========================================
 * TTL INDEX
 * ==========================================
 *
 * Automatically removes expired invitations.
 *
 * MongoDB's TTL monitor normally runs
 * approximately once every 60 seconds.
 *
 * IMPORTANT:
 *
 * This is cleanup only.
 *
 * The controller MUST still check:
 *
 * invitation.expiresAt < Date.now()
 *
 * when accepting an invitation.
 */
StaffInvitationSchema.index(
    {
        expiresAt: 1,
    },
    {
        expireAfterSeconds: 0,
    }
);

/**
 * ==========================================
 * PENDING INVITATION INDEX
 * ==========================================
 *
 * Optimizes queries such as:
 *
 * {
 *     owner,
 *     email,
 *     acceptedAt: null
 * }
 *
 * This is used when checking whether the
 * business owner already has a pending
 * invitation for an email address.
 */
StaffInvitationSchema.index({
    owner: 1,
    email: 1,
    acceptedAt: 1,
});

/**
 * ==========================================
 * OWNER + ACCEPTANCE INDEX
 * ==========================================
 *
 * Useful for listing pending/accepted
 * invitations belonging to a specific owner.
 */
StaffInvitationSchema.index({
    owner: 1,
    acceptedAt: 1,
});

/**
 * ==========================================
 * EXPIRATION VALIDATION
 * ==========================================
 *
 * New invitations must expire in the future.
 *
 * The controller MUST still perform a runtime
 * expiration check when accepting an invitation.
 */
StaffInvitationSchema.path(
    "expiresAt"
).validate({
    validator: function (
        value: Date
    ): boolean {
        return (
            value instanceof Date &&
            !Number.isNaN(
                value.getTime()
            ) &&
            value.getTime() > Date.now()
        );
    },

    message:
        "Invitation expiration time must be in the future.",
});

/**
 * ==========================================
 * MODEL
 * ==========================================
 */

const StaffInvitation =
    mongoose.model<IStaffInvitation>(
        "StaffInvitation",
        StaffInvitationSchema
    );

export default StaffInvitation;